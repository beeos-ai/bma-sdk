#!/usr/bin/env python3
"""Generate the bma-sdk 2.0 Python extension services.

Input: contracts/bma/v2/extensions.openapi.yaml and the resource map
contracts/bma/v2/sdk.resources.yaml (see v2model.py). Models and request
TypedDicts come from pygen.Types (the 1.x type generator) on top of the
official anthropic BaseModel; the services subclass anthropic's
SyncAPIResource / AsyncAPIResource and send every request through the
official client (`self._get`, `self._post`, `self._get_api_list`), so the base
URL, credentials, headers, retries, timeouts, middleware and errors are the
official ones. Methods follow anthropic-sdk-python: create / retrieve /
update / list / delete and path actions in snake_case; path parameters are
positional, body and query fields are keyword arguments.

    python3 tools/sdkgen/py2gen.py <contract> <resources.yaml> <package dir>
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

import pygen
from pygen import PyGenError, Types, pascal, render_models, render_params, snake
from v2model import Model, Op, Service

HEADER = "# Code generated by tools/sdkgen/py2gen.py from contracts/bma/v2/extensions.openapi.yaml; DO NOT EDIT."
pygen.HEADER[:] = [HEADER]


def fix_imports(text: str) -> str:
    text = text.replace("from ..._models import BaseModel, PropertyInfo", "from anthropic import BaseModel")
    text = text.replace("from ..._types import FileTypes", "from anthropic._types import FileTypes")
    # anthropic 2.x annotates its unions without a discriminator.
    return re.sub(r'Annotated\[(.*), PropertyInfo\(discriminator="\w+"\)\]', r"\1", text)


class Gen:
    def __init__(self, model: Model):
        self.m = model
        self.models = Types(model.doc, "model")
        self.params = Types(model.doc, "param")

    def kwargs(self, op: Op) -> list[tuple[str, str, bool]]:
        """(name, type, required) of the keyword arguments."""
        out: list[tuple[str, str, bool]] = []
        for q in op.queries:
            t = self.params.expr(q.schema, pascal(op.op_id) + pascal(q.name))
            if t.startswith("Optional["):
                t = t[len("Optional["):-1]
            out.append((q.name, t, q.required))
        if op.body:
            schema = self.m.schemas[op.body]
            props, required, _ = self.params.collect(schema)
            for prop, schemas in props.items():
                exprs = list(dict.fromkeys(self.params.expr(s, op.body + pascal(prop)) for s in schemas))
                t = exprs[0] if len(exprs) == 1 else f"Union[{', '.join(exprs)}]"
                out.append((prop, t, prop in required))
        names = [n for n, _, _ in out]
        for n in names:
            if names.count(n) > 1 or n in ("extra_headers", "extra_query", "extra_body", "timeout", "idempotency_key"):
                raise PyGenError(f"{op.op_id}: parameter {n} collides")
        return out

    def method(self, svc: Service, op: Op, is_async: bool) -> list[str]:
        name = self.m.method_name(op, "snake")
        kwargs = self.kwargs(op)
        args = ["self"] + [f"{p}: str" for p in op.path_params] + ["*"]
        for n, t, required in sorted(kwargs, key=lambda k: not k[2]):
            args.append(f"{n}: {t}" if required else f"{n}: Union[{t}, Omit] = omit")
        if op.idempotent:
            args.append("idempotency_key: Optional[str] = None")
        args += [
            "extra_headers: Optional[Headers] = None",
            "extra_query: Optional[Query] = None",
            "extra_body: Optional[Body] = None",
            "timeout: Union[float, httpx2.Timeout, None, NotGiven] = not_given",
        ]
        path = "/v1" + op.path
        route = f'path_template("{path}", ' + ", ".join(f"{p}={p}" for p in op.path_params) + ")" if op.path_params else f'"{path}"'
        lines = [f"    {'async def' if is_async and not op.paged else 'def'} {name}({', '.join(args)}) -> RET:"]
        summary = f"{op.summary}." if op.summary else ""
        text = (summary + " " + op.description).strip().replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
        lines.append(f'        """{text}"""')
        for p in op.path_params:
            lines += [f"        if not {p}:", f'            raise ValueError(f"Expected a non-empty value for `{p}` but received {{{p}!r}}")']
        if op.idempotent:
            lines.append('        extra_headers = {"Idempotency-Key": idempotency_key or str(uuid.uuid4()), **(extra_headers or {})}')
        opts = ["extra_headers=extra_headers", "extra_query=extra_query", "extra_body=extra_body", "timeout=timeout"]
        if op.queries:
            opts.append("query={" + ", ".join(f'"{q.name}": {q.name}' for q in op.queries) + "}")
        options = f"make_request_options({', '.join(opts)})"
        body = ""
        if op.body:
            body = "body={" + ", ".join(f'"{n}": {n}' for n, _, _ in kwargs) + "}, "
        aw = "await " if is_async and not op.paged else ""
        if op.paged:
            item = self.models.ref_name(op.response)
            page = ("AsyncPageCursor" if is_async else "SyncPageCursor") + f"[{item}]"
            ret = f"AsyncPaginator[{item}, {page}]" if is_async else page
            lines.append(f'        return self._get_api_list({route}, page={page}, options={options}, model={item})')
        else:
            item = self.models.ref_name(op.response)
            ret = item
            verb = "_" + op.verb
            lines.append(f"        return {aw}self.{verb}({route}, {body}options={options}, cast_to={item})")
        lines[0] = lines[0].replace("RET", ret)
        return lines

    def qualify(self, text: str) -> str:
        params = set(self.params.classes) | set(self.params.aliases)
        models = set(self.models.classes) | set(self.models.aliases)

        def sub(mt: re.Match[str]) -> str:
            w = mt[0]
            if w in params:
                return f"_params.{w}"
            if w in models:
                return f"_models.{w}"
            return w

        return re.sub(r'(?<![.\w"])[A-Za-z_][A-Za-z0-9_]*', sub, text)

    @staticmethod
    def cls(svc: Service, prefix: str) -> str:
        return f"{prefix}{svc.stem}s"

    def render_resources(self) -> str:
        for name in self.m.schemas:
            self.models.schema_type(name)
            if not self.params.plain(name):
                self.params.schema_type(name)
        body: list[str] = []
        for is_async in (False, True):
            prefix = "Async" if is_async else ""
            base = "AsyncAPIResource" if is_async else "SyncAPIResource"
            for svc in self.m.services.values():
                body += ["", "", f"class {self.cls(svc, prefix)}({base}):"]
                lines: list[str] = []
                for child in self.m.children(svc.path):
                    leaf = snake(child.path.rsplit(".", 1)[-1])
                    lines += ["    @cached_property", f"    def {leaf}(self) -> {self.cls(child, prefix)}:", f"        return {self.cls(child, prefix)}(self._client)", ""]
                for op in svc.ops:
                    lines += [self.qualify(line) for line in self.method(svc, op, is_async)] + [""]
                body += lines[:-1] if lines else ["    pass"]
        roots = [s for s in self.m.roots() if "." not in s.path]
        for is_async in (False, True):
            prefix = "Async" if is_async else ""
            base = "AsyncAPIResource" if is_async else "SyncAPIResource"
            body += ["", "", f"class {prefix}ExtensionServices:", '    """The BMA extension resources of client.beta."""', ""]
            body += [f"    def __init__(self, client: {'Async' if is_async else 'Sync'}APIClient) -> None:", "        self._client = client"]
            for svc in roots:
                leaf = snake(svc.path)
                body += ["", "    @cached_property", f"    def {leaf}(self) -> {self.cls(svc, prefix)}:", f"        return {self.cls(svc, prefix)}(self._client)"]
            del base
        head = [
            HEADER,
            "# pyright: reportUnusedImport=false",
            "from __future__ import annotations",
            "",
            "import uuid",
            "from datetime import datetime",
            "from typing import Dict, List, Optional, Union",
            "",
            "import httpx2",
            "from typing_extensions import Literal",
            "from anthropic._types import Body, Omit, Query, Headers, NotGiven, omit, not_given",
            "from anthropic._utils import path_template",
            "from anthropic._compat import cached_property",
            "from anthropic._resource import SyncAPIResource, AsyncAPIResource",
            "from anthropic._base_client import AsyncPaginator, SyncAPIClient, AsyncAPIClient, make_request_options",
            "from anthropic.pagination import SyncPageCursor, AsyncPageCursor",
            "",
            "from . import models as _models",
            "from . import params as _params",
            "",
            '__all__ = [' + ", ".join(f'"{self.cls(s, p)}"' for p in ("", "Async") for s in self.m.services.values()) + ', "ExtensionServices", "AsyncExtensionServices"]',
        ]
        return "\n".join(head + body) + "\n"

    def run(self, out: Path) -> None:
        resources = self.render_resources()
        out.mkdir(parents=True, exist_ok=True)
        (out / "__init__.py").write_text(HEADER + "\n")
        (out / "models.py").write_text(fix_imports(render_models(self.models, [], {})))
        (out / "params.py").write_text(fix_imports(render_params(self.params, "models")))
        (out / "resources.py").write_text(resources)
        print(f"wrote {out}")


def main() -> int:
    if len(sys.argv) != 4:
        print(__doc__, file=sys.stderr)
        return 2
    Gen(Model(Path(sys.argv[1]), Path(sys.argv[2]))).run(Path(sys.argv[3]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
